base_res_dir = "/app/src/main/res"

for lang, str_map in translations.items():
    file_path = os.path.join(base_res_dir, f"values-{lang}", "strings.xml")
    if not os.path.exists(file_path):
        continue
    with open(file_path, "r", encoding="utf-8") as f:
        content = f.read()

    # check if outdoor_spots_title already exists
    if "outdoor_spots_title" in content:
        continue

    # generate xml strings
    xml_lines = ["\n    <!-- Outdoor Spots & Custom Thresholds -->"]
    for k, v in str_map.items():
        xml_lines.append(f'    <string name="{k}">{v}</string>')
    xml_block = "\n".join(xml_lines) + "\n</resources>"

    new_content = content.replace("</resources>", xml_block)
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(new_content)
    print(f"Updated {file_path}")

print("Localization update complete.")
